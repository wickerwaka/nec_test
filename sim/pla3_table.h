// True for every vector the decoder must treat as a PREFIX (consume the byte
// and re-decode the next one) rather than as an instruction.
constexpr bool is_prefix(uint16_t v) {
    if (!one_byte_logic(v)) return false;
    switch (bl1_op(v)) {
        case Bl1Op::kSegPrefix: case Bl1Op::kExtPrefix:
        case Bl1Op::kRepcPfx:   case Bl1Op::kRepncPfx:
        case Bl1Op::kRepPfx:    case Bl1Op::kRepnePfx:
        case Bl1Op::kLockAlias: case Bl1Op::kLock:
            return true;
        default:
            return false;
    }
}

